"""Model registry (M4, plan §16 "model registry manifest", D-036).

Every fitted model has a manifest in ``configs/models/*.yaml`` (written by the experiment script
that fitted it). This module reads them all and checks each one:

- the artifact exists and its SHA-256 equals the manifest's (a tracked artifact must match; a
  local-only artifact, ``artifact_tracked: false``, may be missing and is rebuilt by its script);
- it was trained on the current lap dataset (content hash of ``dataset_laps_2024_v1``);
- whether the engine uses it: ``ENGINE_ARTIFACTS`` lists the files ``setup_from_codes`` loads.
  Each of them is optional: without it the setup falls back to the editorial model and says so
  in ``RaceSetup.inputs`` (tested).
"""

import hashlib
from dataclasses import dataclass
from pathlib import Path
from typing import Any

import yaml

from f1ar.calibration.lap_model_fit import SHAPE_FILE
from f1ar.calibration.race_control_fit import RACE_CONTROL_FILE
from f1ar.calibration.traffic_fit import TRAFFIC_FILE
from f1ar.calibration.weather_fit import WEATHER_FILE

DATASET_MANIFEST = Path("data") / "manifests" / "dataset_laps_2024_v1.yaml"
ENGINE_ARTIFACTS = {
    (Path("configs") / f).as_posix(): what
    for f, what in (
        (SHAPE_FILE, "tyre/fuel lap model (D-033)"),
        (WEATHER_FILE, "weather (D-034)"),
        (TRAFFIC_FILE, "overtaking + launch spread (D-035)"),
        (RACE_CONTROL_FILE, "race control rates (D-035)"),
    )
}
"""Artifacts the engine's setup loads (repo-relative path -> what it drives)."""


@dataclass(frozen=True)
class ModelEntry:
    manifest: str
    model_name: str
    model_version: str
    kind: str
    source_type: str
    status: str
    artifact: str
    artifact_tracked: bool
    artifact_sha256: str
    artifact_found: bool
    artifact_matches: bool
    dataset_sha256: str
    dataset_current: bool
    used_by_engine: str | None
    """What the engine uses it for, or None (analysis / M5 only)."""

    @property
    def problems(self) -> list[str]:
        out = []
        if self.artifact_tracked and not self.artifact_found:
            out.append("tracked artifact missing")
        if self.artifact_found and not self.artifact_matches:
            out.append("artifact hash differs from the manifest")
        if not self.dataset_current:
            out.append("trained on a different lap dataset")
        return out


def _sha(path: Path) -> str:
    # hash the text as written (LF), like the scripts that wrote the manifests
    return "sha256:" + hashlib.sha256(path.read_bytes()).hexdigest()


def load_registry(root: Path) -> list[ModelEntry]:
    dataset = yaml.safe_load((root / DATASET_MANIFEST).read_text(encoding="utf-8"))
    current = str(dataset["file"]["content_sha256"])
    entries = []
    for path in sorted((root / "configs" / "models").glob("*.yaml")):
        m: dict[str, Any] = yaml.safe_load(path.read_text(encoding="utf-8"))
        artifact = str(m["artifact"])
        file = root / artifact
        found = file.exists()
        entries.append(
            ModelEntry(
                manifest=path.relative_to(root).as_posix(),
                model_name=str(m["model_name"]),
                model_version=str(m["model_version"]),
                kind=str(m.get("kind", "")),
                source_type=str(m.get("source_type", "")),
                status=str(m.get("status", "")),
                artifact=artifact,
                artifact_tracked=bool(m.get("artifact_tracked", True)),
                artifact_sha256=str(m["artifact_sha256"]),
                artifact_found=found,
                artifact_matches=found and _sha(file) == m["artifact_sha256"],
                dataset_sha256=str(m.get("training_dataset_content_sha256", "")),
                dataset_current=m.get("training_dataset_content_sha256") == current,
                used_by_engine=ENGINE_ARTIFACTS.get(artifact),
            )
        )
    return entries


def registry_markdown(entries: list[ModelEntry]) -> str:
    lines = [
        "# Model registry",
        "",
        "Generated by `scripts/model_registry.py` from `configs/models/*.yaml` (D-036). Every",
        "model is a fit on the 2024 lap dataset; none is a trained agent (that starts in M5).",
        "",
        "| Model | Kind | Source | Status | Used by the engine | Artifact | Check |",
        "|---|---|---|---|---|---|---|",
    ]
    for e in entries:
        check = "; ".join(e.problems) or (
            "ok" if e.artifact_found else "ok (local only, not built here)"
        )
        lines.append(
            f"| {e.model_name} {e.model_version} | {e.kind} | {e.source_type} | {e.status} | "
            f"{e.used_by_engine or 'no (analysis / M5)'} | `{e.artifact}` "
            f"({'tracked' if e.artifact_tracked else 'local, gitignored'}) | {check} |"
        )
    lines += [
        "",
        "Without any of the engine's artifacts a race still builds: the setup falls back to the",
        "editorial model for that part and labels it `editorial_assumption` in `RaceSetup.inputs`.",
        "",
    ]
    return "\n".join(lines)
